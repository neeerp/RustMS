//! Build the ignored server content pack from the MIT-licensed community
//! sources listed in `game-data/server_content.toml`.
//!
//!     cargo run -p game-data --bin import-server-content -- <sources> [pack]
//!
//! `<sources>` holds checkouts of Edelstein.lua, Server.Scripts, and
//! Server.NX; `[pack]` defaults to `assets/server-content`.

use game_data::lua_strings::string_literals;
use game_data::server_content::keys;
use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const MAPPING: &str = include_str!("../../server_content.toml");

#[derive(Deserialize)]
struct Mapping {
    text: BTreeMap<String, TextSource>,
    rewards: RewardSource,
}

#[derive(Deserialize)]
struct TextSource {
    source: String,
    template: String,
    sha256: String,
}

#[derive(Deserialize)]
struct RewardSource {
    source: String,
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let Some(sources) = args.first().map(PathBuf::from) else {
        eprintln!("usage: import-server-content <sources dir> [pack dir]");
        return ExitCode::FAILURE;
    };
    let pack = args
        .get(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("assets/server-content"));
    match run(&sources, &pack) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("import failed: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run(sources: &Path, pack: &Path) -> Result<(), String> {
    let mapping: Mapping = toml::from_str(MAPPING).map_err(|e| e.to_string())?;
    for key in keys::all() {
        if !mapping.text.contains_key(&key) {
            return Err(format!("server_content.toml has no source for {key}"));
        }
    }

    let mut text = BTreeMap::new();
    for (key, source) in &mapping.text {
        let path = sources.join(&source.source);
        let lua = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let literals = string_literals(&lua).map_err(|e| format!("{}: {e}", path.display()))?;
        let value = fill(&source.template, &literals).map_err(|e| format!("{key}: {e}"))?;
        let digest = format!("{:x}", Sha256::digest(value.as_bytes()));
        if digest != source.sha256 {
            return Err(format!(
                "{key}: text in {} changed upstream (sha256 {digest}); review it and update server_content.toml",
                source.source
            ));
        }
        text.insert(key.clone(), value);
    }

    std::fs::create_dir_all(pack).map_err(|e| e.to_string())?;
    let text_toml = toml::to_string(&text).map_err(|e| e.to_string())?;
    let header = "# Generated by import-server-content. Not for redistribution; see\n# agent_docs/server-content.md.\n";
    std::fs::write(pack.join("text.toml"), format!("{header}{text_toml}"))
        .map_err(|e| e.to_string())?;

    let rewards_dir = sources.join(&mapping.rewards.source);
    let mut rewards: BTreeMap<String, serde_json::Value> = BTreeMap::new();
    for entry in
        std::fs::read_dir(&rewards_dir).map_err(|e| format!("{}: {e}", rewards_dir.display()))?
    {
        let path = entry.map_err(|e| e.to_string())?.path();
        let Some(mob) = path.file_stem().and_then(|s| s.to_str()) else {
            continue;
        };
        let Ok(id) = mob.parse::<i32>() else {
            continue;
        };
        let json = std::fs::read_to_string(&path).map_err(|e| e.to_string())?;
        let value = serde_json::from_str(&json).map_err(|e| format!("{}: {e}", path.display()))?;
        rewards.insert(id.to_string(), value);
    }
    let rewards_json = serde_json::to_string(&rewards).map_err(|e| e.to_string())?;
    std::fs::write(pack.join("rewards.json"), rewards_json).map_err(|e| e.to_string())?;

    println!(
        "Wrote {} text keys and drops for {} mobs to {}",
        text.len(),
        rewards.len(),
        pack.display()
    );
    Ok(())
}

/// Replace `{sN}` with literal N; leave other `{name}` placeholders.
fn fill(template: &str, literals: &[String]) -> Result<String, String> {
    let mut out = String::new();
    let mut rest = template;
    while let Some(start) = rest.find("{s") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        let end = after.find('}').ok_or("unclosed {s")?;
        match after[..end].parse::<usize>() {
            Ok(n) => {
                out.push_str(literals.get(n).ok_or(format!("no string literal {n}"))?);
                rest = &after[end + 1..];
            }
            Err(_) => {
                // A runtime placeholder that happens to start with "s".
                out.push_str("{s");
                rest = after;
            }
        }
    }
    out.push_str(rest);
    Ok(out)
}
