//! The item makers who forge equipment from materials and mesos: Serryl on
//! the Nautilus (1091003), Neve in Orbis (2010003) and Mos in Leafre
//! (2080000). Items, materials and prices follow Cosmic's scripts.

/// One thing a maker makes: an `item` for its `materials` (item and
/// quantity) and `cost` mesos.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Recipe {
    pub item: i32,
    pub materials: &'static [(i32, i16)],
    pub cost: i32,
}

pub(crate) const fn recipe(item: i32, materials: &'static [(i32, i16)], cost: i32) -> Recipe {
    Recipe {
        item,
        materials,
        cost,
    }
}

/// The stimulator Mos adds to a weapon of `item`'s kind.
pub fn stimulator(item: i32) -> Option<i32> {
    Some(match item / 10_000 {
        130 => 4130002,
        131 => 4130003,
        132 => 4130004,
        133 => 4130014,
        137 => 4130010,
        138 => 4130011,
        140 => 4130005,
        141 => 4130006,
        142 => 4130007,
        143 => 4130008,
        144 => 4130009,
        145 => 4130012,
        146 => 4130013,
        147 => 4130015,
        148 => 4130016,
        149 => 4130017,
        _ => return None,
    })
}

