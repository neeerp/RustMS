#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn each_stimulated_item_has_a_stimulator_of_its_kind() {
        for recipe in [MOS_WARRIOR, MOS_BOWMAN, MOS_MAGICIAN, MOS_THIEF, MOS_PIRATE].concat() {
            assert!(stimulator(recipe.item).is_some(), "{}", recipe.item);
        }
        assert_eq!(stimulator(1332049), Some(4130014));
        assert_eq!(stimulator(1472051), Some(4130015));
        assert_eq!(stimulator(1492013), Some(4130017));
        assert_eq!(stimulator(1082103), Some(4130000));
        assert_eq!(stimulator(1072000), Some(4130001));
        assert_eq!(stimulator(1002064), None);
        let stimulated = [
            SARAH_WARRIOR_UPGRADES,
            SARAH_BOWMAN_UPGRADES,
            SARAH_MAGICIAN_UPGRADES,
            SARAH_THIEF_UPGRADES,
            TARA_WARRIOR,
            TARA_BOWMAN,
            TARA_MAGICIAN,
            TARA_THIEF,
            RYDOLE_WARRIOR,
            RYDOLE_BOWMAN,
            RYDOLE_MAGICIAN,
            RYDOLE_THIEF_STIMULATED,
        ];
        for recipe in stimulated.concat() {
            assert!(stimulator(recipe.item).is_some(), "{}", recipe.item);
        }
        // Rydole's stimulator goes with the weapon's manual.
        for recipe in [
            RYDOLE_WARRIOR,
            RYDOLE_BOWMAN,
            RYDOLE_MAGICIAN,
            RYDOLE_THIEF_STIMULATED,
        ]
        .concat()
        {
            assert_eq!(
                stimulator(recipe.item),
                Some(recipe.materials[0].0 - 998),
                "{}",
                recipe.item
            );
        }
    }
}
